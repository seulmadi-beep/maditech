// Weekly project sync for the MadiTech site.
// Reads only the repositories listed in projects/approved-projects.json, records their public
// GitHub facts in projects/github-snapshot.json and regenerates the inline project data in
// index.html. Card copy is hand-written in the approved list and is never rewritten here.
// Usage: node scripts/sync-projects.mjs [--summary path/to/summary.md]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const START = '/* GITHUB-PROJECTS:START generated by scripts/sync-projects.mjs from projects/approved-projects.json */';
export const END = '/* GITHUB-PROJECTS:END */';
const CATEGORIES = ['ai', 'robotics', 'studio', 'apps'];
const STATUSES = ['live', 'prototype', 'concept', 'archived'];

export function validateApproved(approved) {
  if (!approved || typeof approved.owner !== 'string' || !Array.isArray(approved.projects)) throw new Error('approved-projects.json needs owner and projects');
  const seen = new Set();
  for (const p of approved.projects) {
    if (!/^[A-Za-z0-9._-]+$/.test(p.repo || '')) throw new Error(`Invalid repo name: ${p.repo}`);
    if (seen.has(p.repo)) throw new Error(`Duplicate repo: ${p.repo}`);
    seen.add(p.repo);
    if (!CATEGORIES.includes(p.category)) throw new Error(`${p.repo}: category must be one of ${CATEGORIES.join(', ')}`);
    if (!STATUSES.includes(p.status)) throw new Error(`${p.repo}: status must be one of ${STATUSES.join(', ')}`);
    if (p.demo !== null && !/^https:\/\/[^\s"'<>]+$/.test(p.demo || '')) throw new Error(`${p.repo}: demo must be null or an https URL`);
    for (const lang of ['en', 'fr', 'fa']) {
      const c = p.copy?.[lang];
      if (!c || !c.name?.trim() || !c.summary?.trim()) throw new Error(`${p.repo}: missing ${lang} copy`);
    }
  }
}

async function getJson(fetchImpl, url, token) {
  const headers = { Accept: 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28', 'User-Agent': 'maditech-project-sync' };
  if (token) headers.Authorization = `Bearer ${token}`;
  const response = await fetchImpl(url, { headers });
  if (response.status === 404) return null;
  if (!response.ok) throw new Error(`GitHub API ${response.status} for ${url}`);
  return response.json();
}

// Collects only public facts. A repository that is missing or private is reported as unavailable
// and is left off the site, so nothing private is ever written to this public repository.
export async function collectFacts(approved, { fetchImpl = fetch, token = '' } = {}) {
  const facts = {};
  for (const p of approved.projects) {
    const base = `https://api.github.com/repos/${approved.owner}/${p.repo}`;
    const repo = await getJson(fetchImpl, base, token);
    if (!repo || repo.private || repo.visibility !== 'public') { facts[p.repo] = { available: false }; continue; }
    const readme = await getJson(fetchImpl, `${base}/readme`, token);
    facts[p.repo] = {
      available: true,
      url: repo.html_url,
      description: repo.description || '',
      homepage: repo.homepage || '',
      language: repo.language || '',
      archived: Boolean(repo.archived),
      defaultBranch: repo.default_branch,
      updated: String(repo.pushed_at || '').slice(0, 7),
      readmeSha: readme?.sha || ''
    };
  }
  return facts;
}

export function siteData(approved, facts) {
  return approved.projects.filter(p => facts[p.repo]?.available).map(p => {
    const f = facts[p.repo];
    return {
      repo: p.repo,
      url: f.url,
      category: p.category,
      status: f.archived ? 'archived' : p.status,
      demo: p.demo,
      updated: p.showUpdated ? f.updated : '',
      language: f.language,
      copy: p.copy
    };
  });
}

export function replaceBlock(html, data) {
  const start = html.indexOf(START), end = html.indexOf(END);
  if (start < 0 || end < start) throw new Error('index.html is missing the GITHUB-PROJECTS markers');
  // Escape "<" so no project text can close the inline script.
  const json = JSON.stringify(data).replace(/</g, '\\u003c');
  return html.slice(0, start) + START + '\nconst githubProjects=' + json + ';\n' + html.slice(end);
}

export function summarize(approved, before, after) {
  const lines = [];
  const review = [];
  for (const p of approved.projects) {
    const a = before[p.repo] || {}, b = after[p.repo] || {};
    const changed = Object.keys({ ...a, ...b }).filter(k => JSON.stringify(a[k]) !== JSON.stringify(b[k]));
    if (!changed.length) continue;
    lines.push(`### ${approved.owner}/${p.repo}`);
    for (const k of changed) lines.push(`- \`${k}\`: ${JSON.stringify(a[k] ?? null)} → ${JSON.stringify(b[k] ?? null)}`);
    if (b.available === false) review.push(`- **${p.repo}** is no longer public or was not found, so it was removed from the site.`);
    if (changed.some(k => ['description', 'readmeSha', 'homepage', 'archived'].includes(k))) review.push(`- **${p.repo}**: its description, README, homepage or archive state changed. Review the EN/FR/FA copy, status and demo link in \`projects/approved-projects.json\` before merging.`);
  }
  if (!lines.length) return '';
  return ['## Approved project changes', '', ...lines, '', ...(review.length ? ['## Needs a human check', '', ...review, ''] : []),
    'Only repositories in `projects/approved-projects.json` were checked. Nothing was deployed; Render publishes only after this pull request is reviewed and merged into main.', ''].join('\n');
}

async function main() {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const approvedPath = resolve(root, 'projects/approved-projects.json');
  const snapshotPath = resolve(root, 'projects/github-snapshot.json');
  const indexPath = resolve(root, 'index.html');
  const approved = JSON.parse(readFileSync(approvedPath, 'utf8'));
  validateApproved(approved);
  const before = existsSync(snapshotPath) ? JSON.parse(readFileSync(snapshotPath, 'utf8')).projects || {} : {};
  const facts = await collectFacts(approved, { token: process.env.GITHUB_TOKEN || '' });
  writeFileSync(snapshotPath, JSON.stringify({ owner: approved.owner, projects: facts }, null, 2) + '\n');
  const html = readFileSync(indexPath, 'utf8');
  const next = replaceBlock(html, siteData(approved, facts));
  if (next !== html) writeFileSync(indexPath, next);
  const summaryArg = process.argv.indexOf('--summary');
  let summary = summarize(approved, before, facts);
  if (!summary && next !== html) summary = '## Site data regenerated\n\nThe inline project cards in index.html were rebuilt from `projects/approved-projects.json`. No GitHub facts changed.\n';
  if (summaryArg > 0) writeFileSync(process.argv[summaryArg + 1], summary);
  console.log(summary || 'No changes in approved projects.');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error.message); process.exit(1); });
}
